#!/usr/bin/env bash
# Project-local MySQL instance for JARVIS development and tests.
#
# It is completely separate from any MySQL server already on this machine:
# its own data directory (.jarvis-data/mysql), its own port (3307, loopback
# only) and its own randomly generated credentials. Nothing here reads or
# changes another server's data or accounts.
#
# Usage: scripts/dev-db.sh <init|start|stop|status|seed|reset>
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BASE="$ROOT/.jarvis-data/mysql"
DATA="$BASE/data"
RUN="$BASE/run"
SOCKET="$RUN/mysql.sock"
PID_FILE="$RUN/mysqld.pid"
ROOT_CNF="$BASE/root.cnf"
ENV_FILE="$ROOT/.env.test"
PORT="${JARVIS_DEV_DB_PORT:-3307}"
DEV_USER="jarvis_dev"
DEMO_DB="jarvis_demo"

need() { command -v "$1" >/dev/null || { echo "error: '$1' not found. Install MySQL 8 (e.g. brew install mysql@8.0)." >&2; exit 1; }; }
need mysqld; need mysql; need openssl

running() { [[ -f "$PID_FILE" ]] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; }
root_sql() { mysql --defaults-extra-file="$ROOT_CNF" "$@"; }
random_secret() { openssl rand -hex 18; }

start() {
  [[ -d "$DATA" ]] || { echo "error: not initialised. Run: scripts/dev-db.sh init" >&2; exit 1; }
  if running; then echo "dev MySQL already running on 127.0.0.1:$PORT"; return; fi
  mkdir -p "$RUN"
  mysqld --no-defaults --datadir="$DATA" --port="$PORT" --bind-address=127.0.0.1 \
    --socket="$SOCKET" --pid-file="$PID_FILE" --mysqlx=OFF \
    --log-error="$BASE/error.log" --daemonize
  for _ in $(seq 1 60); do [[ -S "$SOCKET" ]] && break; sleep 0.5; done
  [[ -S "$SOCKET" ]] || { echo "error: mysqld did not start; see $BASE/error.log" >&2; exit 1; }
  echo "dev MySQL started on 127.0.0.1:$PORT"
}

stop() {
  if ! running; then echo "dev MySQL is not running"; return; fi
  local pid; pid="$(cat "$PID_FILE")"
  kill "$pid"
  for _ in $(seq 1 60); do kill -0 "$pid" 2>/dev/null || break; sleep 0.5; done
  echo "dev MySQL stopped"
}

init() {
  if [[ -d "$DATA" ]]; then echo "already initialised at $BASE (use 'reset' to wipe it)"; return; fi
  mkdir -p "$BASE" "$RUN"; chmod 700 "$ROOT/.jarvis-data" "$BASE"
  echo "initialising data directory…"
  mysqld --no-defaults --initialize-insecure --datadir="$DATA" --log-error="$BASE/init.log"
  start

  local root_pw dev_pw
  root_pw="$(random_secret)"; dev_pw="$(random_secret)"
  mysql --no-defaults -uroot --socket="$SOCKET" <<SQL
ALTER USER 'root'@'localhost' IDENTIFIED BY '$root_pw';
CREATE USER '$DEV_USER'@'localhost' IDENTIFIED BY '$dev_pw';
CREATE USER '$DEV_USER'@'127.0.0.1' IDENTIFIED BY '$dev_pw';
GRANT ALL PRIVILEGES ON \`jarvis\\_%\`.* TO '$DEV_USER'@'localhost';
GRANT ALL PRIVILEGES ON \`jarvis\\_%\`.* TO '$DEV_USER'@'127.0.0.1';
FLUSH PRIVILEGES;
SQL
  ( umask 077
    printf '[client]\nuser=root\npassword=%s\nsocket=%s\n' "$root_pw" "$SOCKET" > "$ROOT_CNF"
    cat > "$ENV_FILE" <<ENV
# Generated by scripts/dev-db.sh — credentials for the project-local dev MySQL instance.
JARVIS_TEST_MYSQL_HOST=127.0.0.1
JARVIS_TEST_MYSQL_PORT=$PORT
JARVIS_TEST_MYSQL_USER=$DEV_USER
JARVIS_TEST_MYSQL_PASSWORD=$dev_pw
JARVIS_TEST_MYSQL_DATABASE=$DEMO_DB
ENV
  )
  seed
  echo "ready. Credentials written to .env.test (git-ignored)."
}

seed() {
  running || start
  root_sql < "$ROOT/scripts/dev-db-seed.sql"
  echo "seeded database '$DEMO_DB'"
}

case "${1:-}" in
  init) init ;;
  start) start ;;
  stop) stop ;;
  seed) seed ;;
  status) if running; then echo "running on 127.0.0.1:$PORT (pid $(cat "$PID_FILE"))"; else echo "stopped"; fi ;;
  reset) stop; rm -rf "$BASE" "$ENV_FILE"; init ;;
  *) echo "usage: $0 <init|start|stop|status|seed|reset>" >&2; exit 2 ;;
esac
